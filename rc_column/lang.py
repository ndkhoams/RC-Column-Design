def T(vi: str, lang: str = None) -> str:
    """Trả về chuỗi theo ngôn ngữ hiện tại (lang=None) hoặc ngôn ngữ chỉ định.

    lang="EN": tra bảng STRINGS; lang="VN" (hoặc giá trị khác): trả nguyên vi.
    """
    if lang is None:
        lang = LANG
    if lang == "EN":
        return STRINGS.get(vi, {}).get("EN", vi)
    return vi

def set_lang(lang: str):
    global LANG
    LANG = lang
